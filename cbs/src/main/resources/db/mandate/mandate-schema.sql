-- Payment mandates: standing orders, direct debits, and sweeps.
-- Apply this script before starting CBS. Hibernate ddl-auto is validate, so these tables must already exist.

CREATE SCHEMA IF NOT EXISTS mandate;

CREATE SEQUENCE IF NOT EXISTS mandate.mandate_reference_sequence AS bigint START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS mandate.payment_mandates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference varchar(50) NOT NULL,
    debtor_account_id bigint NOT NULL,
    creditor_account_id bigint,
    currency_id bigint NOT NULL,
    kind varchar(30) NOT NULL,
    status varchar(20) NOT NULL,
    creditor_scheme varchar(30) NOT NULL,
    frequency varchar(20) NOT NULL,
    amount_type varchar(30) NOT NULL,
    amount numeric(19, 2) NOT NULL,
    day_of_month integer,
    day_of_week integer,
    start_date date NOT NULL,
    end_date date,
    schedule_anchor date,
    next_collection_date date,
    holiday_adjustment varchar(20) NOT NULL,
    cap_behaviour varchar(20) NOT NULL,
    min_amount numeric(19, 2),
    max_amount numeric(19, 2),
    monthly_cap numeric(19, 2),
    collection_fee numeric(19, 2),
    failure_count integer NOT NULL,
    max_retries integer NOT NULL,
    external_creditor_name varchar(140),
    external_creditor_iban varchar(34),
    narrative varchar(255),
    opened_at timestamptz NOT NULL,
    suspended_at timestamptz,
    cancelled_at timestamptz,
    completed_at timestamptz,
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_payment_mandates_reference UNIQUE (reference)
);

CREATE INDEX IF NOT EXISTS idx_payment_mandates_debtor ON mandate.payment_mandates (debtor_account_id);
CREATE INDEX IF NOT EXISTS idx_payment_mandates_creditor ON mandate.payment_mandates (creditor_account_id);
CREATE INDEX IF NOT EXISTS idx_payment_mandates_due ON mandate.payment_mandates (status, next_collection_date);

CREATE TABLE IF NOT EXISTS mandate.mandate_executions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandate_id bigint NOT NULL,
    collection_date date NOT NULL,
    scheduled_date date,
    amount numeric(19, 2),
    fee_amount numeric(19, 2),
    status varchar(20) NOT NULL,
    skip_reason varchar(40),
    transaction_id bigint,
    transaction_reference varchar(64),
    fee_transaction_id bigint,
    reversal_transaction_id bigint,
    fee_reversal_transaction_id bigint,
    idempotency_key varchar(100),
    failure_detail varchar(500),
    attempt_count integer NOT NULL,
    last_attempt_on date,
    attempted_at timestamptz,
    recall_reason varchar(40),
    created_at timestamptz NOT NULL,
    CONSTRAINT uk_mandate_exec_date UNIQUE (mandate_id, collection_date)
);

CREATE INDEX IF NOT EXISTS idx_mandate_executions_mandate ON mandate.mandate_executions (mandate_id);
CREATE INDEX IF NOT EXISTS idx_mandate_executions_status ON mandate.mandate_executions (status);

CREATE TABLE IF NOT EXISTS mandate.mandate_amendments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandate_id bigint NOT NULL,
    kind varchar(30) NOT NULL,
    previous_value varchar(255),
    new_value varchar(255),
    reason varchar(500) NOT NULL,
    amended_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mandate_amendments_mandate ON mandate.mandate_amendments (mandate_id);

CREATE TABLE IF NOT EXISTS mandate.mandate_status_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mandate_id bigint NOT NULL,
    from_status varchar(20),
    to_status varchar(20) NOT NULL,
    reason varchar(500),
    changed_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_mandate_status_history_mandate ON mandate.mandate_status_history (mandate_id);
